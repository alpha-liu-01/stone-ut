def load_group(path, ids):
    for line in open(path):
        parts = line.strip().split(":")
        if len(parts) >= 3 and parts[2].isdigit():
            ids.setdefault(parts[0], int(parts[2]))


def resolve(name, ids):
    if name.startswith("oem_") and name[4:].isdigit():
        return int(name[4:])
    return ids.get(name)


def entries(path):
    for raw in open(path, errors="replace"):
        f = raw.split("#", 1)[0].split()
        if len(f) == 4 and f[0].startswith("/dev/"):
            yield f


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--group", action="append", default=[])
    ap.add_argument("ueventd", nargs="+")
    a = ap.parse_args()
    ids = dict(AID)
    for g in a.group:
        load_group(g, ids)

    rules = {}
    for path in a.ueventd:
        for node, mode, user, group in entries(path):
            uid, gid = resolve(user, ids), resolve(group, ids)
            if uid is None or gid is None:
                print(f"# skipped {node}: unknown id {user}:{group}",
                      file=sys.stderr)
                continue
            rules[node] = (mode, uid, gid, path)

    print("# Generated by tools/ueventd-to-udev.py from:")
    for path in a.ueventd:
        print(f"#   {path}")
    for node, (mode, uid, gid, _) in rules.items():
        print(f'ACTION=="add", ENV{{DEVNAME}}=="{node}", '
              f'OWNER="{uid}", GROUP="{gid}", MODE="{mode}"')


if __name__ == "__main__":
    main()
